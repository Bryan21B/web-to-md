import test from "node:test";
import assert from "node:assert/strict";
import { parseJson3Captions, parseYouTubeVideoId, pickCaptionTrack, segmentsToMarkdown } from "../src/lib/youtube";

const ID = "dQw4w9WgXcQ";

test("parseYouTubeVideoId handles the common URL shapes", () => {
  for (const url of [
    `https://www.youtube.com/watch?v=${ID}`,
    `https://www.youtube.com/watch?list=PL1&v=${ID}&t=42s`,
    `https://m.youtube.com/watch?v=${ID}`,
    `https://music.youtube.com/watch?v=${ID}`,
    `https://youtu.be/${ID}?si=abc`,
    `https://www.youtube.com/shorts/${ID}`,
    `https://www.youtube.com/live/${ID}`,
    `https://www.youtube.com/embed/${ID}`,
  ]) {
    assert.equal(parseYouTubeVideoId(url), ID, url);
  }
});

test("parseYouTubeVideoId rejects non-video pages", () => {
  for (const url of [
    "https://www.youtube.com/",
    "https://www.youtube.com/@channel",
    "https://www.youtube.com/watch?v=short",
    `https://evil-youtube.com/watch?v=${ID}`,
    "not a url",
  ]) {
    assert.equal(parseYouTubeVideoId(url), null, url);
  }
});

test("parseJson3Captions joins segs and skips line-break-only events", () => {
  const segments = parseJson3Captions({
    events: [
      { tStartMs: 0, segs: [{ utf8: "hello" }, { utf8: " world\n" }] },
      { tStartMs: 1000, segs: [{ utf8: "\n" }] },
      { tStartMs: 2000 },
      { tStartMs: 3000, segs: [{ utf8: "again" }] },
    ],
  });
  assert.deepEqual(segments, [
    { startMs: 0, text: "hello world" },
    { startMs: 3000, text: "again" },
  ]);
  assert.deepEqual(parseJson3Captions(null), []);
});

test("segmentsToMarkdown leads paragraphs with a deep link and escapes markup", () => {
  const md = segmentsToMarkdown(
    [
      { startMs: 65_000, text: "use *stars* and [brackets]" },
      { startMs: 3_725_000, text: "later" },
    ],
    ID,
  );
  assert.equal(md, `[01:05](https://www.youtube.com/watch?v=${ID}&t=65s) use \\*stars\\* and \\[brackets\\] later`);
});

test("segmentsToMarkdown breaks long text into paragraphs at sentence ends", () => {
  const sentence = { startMs: 0, text: "x".repeat(300) + "." };
  const md = segmentsToMarkdown([sentence, { ...sentence, startMs: 10_000 }, { ...sentence, startMs: 3_700_000 }], ID);
  const paragraphs = md.split("\n\n");
  assert.equal(paragraphs.length, 2);
  assert.match(paragraphs[1], /^\[1:01:40\]/);
});

const track = (languageCode: string, opts: { asr?: boolean; original?: boolean } = {}) => ({
  baseUrl: `https://x/${languageCode}${opts.asr ? "-asr" : ""}`,
  languageCode,
  label: languageCode,
  isAutoGenerated: !!opts.asr,
  isDefault: !!opts.original,
});

test("pickCaptionTrack auto mode takes the original language, uploaded captions first", () => {
  const tracks = [track("ar", { asr: true }), track("en", { asr: true, original: true }), track("en"), track("de-DE")];
  assert.equal(pickCaptionTrack(tracks)?.baseUrl, "https://x/en");
  assert.equal(pickCaptionTrack(tracks, { mode: "auto", language: "de" })?.baseUrl, "https://x/en");
});

test("pickCaptionTrack auto mode uses the backup language when the original is unknown", () => {
  const tracks = [track("ar", { asr: true }), track("fr", { asr: true })];
  assert.equal(pickCaptionTrack(tracks, { mode: "auto", language: "fr" })?.languageCode, "fr");
  assert.equal(pickCaptionTrack(tracks, { mode: "auto", language: "ja" })?.languageCode, "ar");
});

test("pickCaptionTrack fixed mode takes the chosen language, else the original", () => {
  const tracks = [track("ar", { asr: true }), track("en", { asr: true, original: true }), track("pt-BR")];
  assert.equal(pickCaptionTrack(tracks, { mode: "fixed", language: "pt" })?.languageCode, "pt-BR");
  assert.equal(pickCaptionTrack(tracks, { mode: "fixed", language: "PT-br" })?.languageCode, "pt-BR");
  assert.equal(pickCaptionTrack(tracks, { mode: "fixed", language: "ja" })?.languageCode, "en");
  assert.equal(pickCaptionTrack([], { mode: "fixed", language: "en" }), undefined);
});
