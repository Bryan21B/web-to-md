import { buildFrontmatter, combineFrontmatterAndBody } from "./frontmatter";
import type { CommandPreferences } from "./types";

const TIMEOUT_MS = 20_000;

// The public web player now gates caption downloads behind a proof-of-origin
// token. The Android client's player response still carries pre-signed
// caption URLs, so ask for that one instead. If YouTube changes this again,
// this is the first place to look.
const INNERTUBE_PLAYER_URL = "https://www.youtube.com/youtubei/v1/player?prettyPrint=false";
const INNERTUBE_CLIENT = { clientName: "ANDROID", clientVersion: "20.10.38" };

const VIDEO_ID = /^[A-Za-z0-9_-]{11}$/;
const YOUTUBE_HOSTS = new Set(["youtube.com", "www.youtube.com", "m.youtube.com", "music.youtube.com"]);

export type CaptionTrack = {
  baseUrl: string;
  languageCode: string;
  /** Human-readable name, e.g. "English (auto-generated)". */
  label: string;
  /** Speech-recognition captions, as opposed to ones the uploader provided. */
  isAutoGenerated: boolean;
  /** YouTube's default track for the video's original audio. */
  isDefault: boolean;
};

export type TranscriptSegment = {
  startMs: number;
  text: string;
};

/** The 11-character video id for any common YouTube URL shape, else null. */
export function parseYouTubeVideoId(url: string): string | null {
  let u: URL;
  try {
    u = new URL(url);
  } catch {
    return null;
  }

  const host = u.hostname.toLowerCase();
  let candidate: string | null = null;

  if (host === "youtu.be") {
    candidate = u.pathname.split("/")[1] ?? null;
  } else if (YOUTUBE_HOSTS.has(host)) {
    if (u.pathname === "/watch") {
      candidate = u.searchParams.get("v");
    } else {
      const match = u.pathname.match(/^\/(?:shorts|live|embed|v)\/([^/?#]+)/);
      candidate = match?.[1] ?? null;
    }
  }

  return candidate && VIDEO_ID.test(candidate) ? candidate : null;
}

export type TranscriptLanguageMode = "auto" | "fixed";

/**
 * Picks which caption track to download.
 *
 * - "auto": the video's original language; `language` is the backup when
 *   YouTube does not say which track is the original.
 * - "fixed": `language` whenever the video has it; otherwise the original.
 *
 * Within a language, uploaded captions beat speech recognition. Translation
 * is not an option: YouTube rate-limits translated caption requests.
 */
export function pickCaptionTrack(
  tracks: CaptionTrack[],
  options: { mode?: TranscriptLanguageMode; language?: string } = {},
): CaptionTrack | undefined {
  const { mode = "auto", language } = options;

  // Array.sort is stable, so YouTube's order still breaks ties.
  const ranked = [...tracks].sort((a, b) => Number(a.isAutoGenerated) - Number(b.isAutoGenerated));
  const base = (code: string) => code.toLowerCase().split("-")[0];

  const inLanguage = (code: string | undefined) => {
    if (!code) return undefined;
    const wanted = code.toLowerCase();
    return (
      ranked.find((t) => t.languageCode.toLowerCase() === wanted) ??
      ranked.find((t) => base(t.languageCode) === base(wanted))
    );
  };

  // Auto-dubbed videos carry a speech-recognition track per dub, listed
  // alphabetically, so "first" can be Arabic for an English talk.
  const original = tracks.find((t) => t.isDefault);
  const originalTrack = original && (inLanguage(original.languageCode) ?? original);
  const chosenTrack = inLanguage(language);

  const order = mode === "fixed" ? [chosenTrack, originalTrack] : [originalTrack, chosenTrack];

  // Better a transcript in another language than none at all; the track
  // label in the output says which language it is.
  return order.find(Boolean) ?? ranked[0];
}

/** Flattens a `fmt=json3` caption payload into timed text segments. */
export function parseJson3Captions(payload: unknown): TranscriptSegment[] {
  const events = (payload as { events?: unknown[] })?.events;
  if (!Array.isArray(events)) return [];

  const segments: TranscriptSegment[] = [];
  for (const raw of events) {
    const event = raw as { tStartMs?: number; segs?: { utf8?: string }[] };
    if (!Array.isArray(event.segs)) continue;

    const text = event.segs
      .map((seg) => seg.utf8 ?? "")
      .join("")
      .replace(/\s+/g, " ")
      .trim();
    // Auto-generated tracks interleave "\n"-only events to drive line breaks.
    if (!text) continue;

    segments.push({ startMs: event.tStartMs ?? 0, text });
  }
  return segments;
}

/**
 * Joins caption lines into readable paragraphs, each led by a timestamp that
 * links back to that moment in the video. Caption lines are a few words each,
 * so one-per-line output is unreadable and bloats the file.
 */
export function segmentsToMarkdown(segments: TranscriptSegment[], videoId: string): string {
  const SOFT_LIMIT = 500; // break at the next sentence end once past this
  const HARD_LIMIT = 1000; // break regardless

  const paragraphs: string[] = [];
  let startMs = 0;
  let buffer: string[] = [];
  let length = 0;

  const flush = () => {
    if (buffer.length === 0) return;
    paragraphs.push(`${timestampLink(startMs, videoId)} ${buffer.join(" ")}`);
    buffer = [];
    length = 0;
  };

  for (const segment of segments) {
    if (buffer.length === 0) startMs = segment.startMs;
    buffer.push(escapeMarkdown(segment.text));
    length += segment.text.length + 1;

    const endsSentence = /[.!?…]["')\]]?$/.test(segment.text);
    if ((length >= SOFT_LIMIT && endsSentence) || length >= HARD_LIMIT) flush();
  }
  flush();

  return paragraphs.join("\n\n");
}

function timestampLink(ms: number, videoId: string): string {
  const total = Math.floor(ms / 1000);
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  const pad = (n: number) => String(n).padStart(2, "0");
  const label = h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${pad(m)}:${pad(s)}`;
  return `[${label}](https://www.youtube.com/watch?v=${videoId}&t=${total}s)`;
}

function escapeMarkdown(text: string): string {
  // Spoken text has no markup of its own, so anything Markdown would act on
  // ("*", "[", "<" …) is literal and must stay that way.
  return text.replace(/([\\`*_[\]<>|])/g, "\\$1");
}

async function fetchJson(url: string, init?: RequestInit): Promise<unknown> {
  let res: Response;
  try {
    res = await fetch(url, { ...init, signal: AbortSignal.timeout(TIMEOUT_MS) });
  } catch (err) {
    if (err instanceof Error && err.name === "TimeoutError") {
      throw new Error(`YouTube did not answer within ${TIMEOUT_MS / 1000}s.`);
    }
    throw err;
  }
  if (!res.ok) throw new Error(`YouTube request failed (${res.status} ${res.statusText})`);
  return res.json();
}

type PlayerResponse = {
  playabilityStatus?: { status?: string; reason?: string };
  videoDetails?: { title?: string; author?: string; shortDescription?: string };
  captions?: {
    playerCaptionsTracklistRenderer?: {
      audioTracks?: { captionTrackIndices?: number[] }[];
      defaultAudioTrackIndex?: number;
      captionTracks?: {
        baseUrl?: string;
        languageCode?: string;
        kind?: string;
        name?: { simpleText?: string; runs?: { text?: string }[] };
      }[];
    };
  };
};

function readCaptionTracks(player: PlayerResponse): CaptionTrack[] {
  const renderer = player.captions?.playerCaptionsTracklistRenderer;
  const raw = renderer?.captionTracks ?? [];
  // Each audio track lists its caption tracks best-first; the default audio
  // is the original (non-dubbed) one.
  const defaultIndex = renderer?.audioTracks?.[renderer.defaultAudioTrackIndex ?? 0]?.captionTrackIndices?.[0];

  return raw
    .map((t, index) => ({ ...t, isDefault: index === defaultIndex }))
    .filter((t): t is typeof t & { baseUrl: string; languageCode: string } => !!t.baseUrl && !!t.languageCode)
    .map((t) => ({
      baseUrl: t.baseUrl,
      languageCode: t.languageCode,
      label: t.name?.simpleText ?? t.name?.runs?.map((r) => r.text ?? "").join("") ?? t.languageCode,
      isAutoGenerated: t.kind === "asr",
      isDefault: t.isDefault,
    }));
}

export async function convertYouTubeTranscript(options: {
  url: string;
  preferences: CommandPreferences;
  onProgress?: (message: string) => void;
}): Promise<ConversionResult> {
  const { url, preferences, onProgress } = options;

  const videoId = parseYouTubeVideoId(url);
  if (!videoId) throw new Error("This is not a YouTube video page.");
  const watchUrl = `https://www.youtube.com/watch?v=${videoId}`;

  onProgress?.("Looking up captions…");
  const player = (await fetchJson(INNERTUBE_PLAYER_URL, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ context: { client: INNERTUBE_CLIENT }, videoId }),
  })) as PlayerResponse;

  const status = player.playabilityStatus?.status;
  if (status && status !== "OK") {
    throw new Error(player.playabilityStatus?.reason || `YouTube refused the video (${status}).`);
  }

  const tracks = readCaptionTracks(player);
  if (tracks.length === 0) throw new Error("This video has no captions.");

  const track = pickCaptionTrack(tracks, {
    mode: preferences.transcriptLanguageMode,
    language: preferences.transcriptLanguage,
  });
  if (!track) throw new Error("No caption track matched.");

  onProgress?.(`Downloading ${track.label} captions…`);
  const captionUrl = new URL(track.baseUrl);
  captionUrl.searchParams.set("fmt", "json3");
  const segments = parseJson3Captions(await fetchJson(captionUrl.toString()));
  if (segments.length === 0) throw new Error(`The ${track.label} caption track is empty.`);

  const title = player.videoDetails?.title;
  const channel = player.videoDetails?.author;

  const header = [
    `# ${escapeMarkdown(title ?? "YouTube transcript")}`,
    [channel && escapeMarkdown(channel), track.label].filter(Boolean).join(" · "),
  ].join("\n\n");
  const body = `${header}\n\n${segmentsToMarkdown(segments, videoId)}\n`;

  const frontmatter = buildFrontmatter(
    { title, author: channel, sourceUrl: watchUrl, bodyMarkdown: body },
    preferences.includeFrontmatter ?? false,
  );

  return {
    markdown: combineFrontmatterAndBody(frontmatter, body),
    body,
    title: title ? `${title} (transcript)` : undefined,
    url: watchUrl,
  };
}
